# Tipo de dado bool (boolean)

# Ao questionar algo em um programa,
# só existem duas respostas possíveis:
# True (verdadeiro) ou False (falso).

# O operador == verifica se um valor
# é igual a outro.

print(10 == 10) # Sim => True
print(10 == 5) # Não => False
print(type(True))
print(type(False))
print(type(10 == 10))
print(type(10 == 11))