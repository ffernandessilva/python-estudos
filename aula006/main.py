# Variáveis são usadas para armazenar dados na memória.

# PEP 8:
# Use letras minúsculas e underscore (_)
# para nomear variáveis.

# O sinal = é o operador de atribuição.
# Ele atribui um valor a uma variável.

# Sintaxe:
# nome_variavel = expressão

nome_completo = 'Felipe Fernandes Silva'
soma = 2 + 2
int_um = int('1')

print(int_um, type(int_um))
print(nome_completo, soma)

