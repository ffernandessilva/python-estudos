# Adição (+)
adicao = 10 + 10
print('Adição:', adicao)

# Subtração (-)
subtracao = 10 - 5
print('Subtração:', subtracao)

# Multiplicação (*)
multiplicacao = 10 * 10
print('Multiplicação:', multiplicacao)

# Divisão (/)
divisao = 10 / 2.2
print('Divisão:', divisao)

# Divisão inteira (//)
divisao_inteira = 10 // 2.2
print('Divisão inteira:', divisao_inteira)

# Exponenciação (**)
exponenciacao = 2 ** 10
print('Exponenciação:', exponenciacao)

# Módulo (%) -> Resto da divisão
modulo = 55 % 2
print('Módulo:', modulo)